function getRankInfo(count) {
  for (let i = 0; i < RANK_TABLE.length; i++) {
    const tier = RANK_TABLE[i];
    if (count >= tier.min && (tier.max === null || count <= tier.max)) return tier;
  }
  return RANK_TABLE[RANK_TABLE.length - 1];
}

